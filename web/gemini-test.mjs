import assert from "node:assert/strict";
import {geminiConfig} from "./gemini-config.mjs";
import {configured,cloudIntent,eligible} from "./gemini-router.mjs";
assert.equal(configured(geminiConfig),false);
const config={enabled:true,sparkVerified:true,appCheckEnforced:true,appId:"1:123:web:abcdef",recaptchaSiteKey:"public-test-key-long-enough"};
let calls=0,auth=true;
const opts={config,consent:true,authorized:()=>auth,generate:async prompt=>{calls++;assert.ok(prompt.includes("Which trucks can take loads"));assert.ok(!prompt.includes("trip records"));return "available";}};
assert.equal(await cloudIntent("Which trucks can take loads", {...opts,config:geminiConfig}),null);
assert.equal(await cloudIntent("Which trucks can take loads", {...opts,consent:false}),null);
assert.equal(await cloudIntent("Delete all trips",opts),null);
assert.equal(await cloudIntent("KA51 1234",opts),null);
assert.equal(await cloudIntent("Revenue last year",opts),null);
assert.equal(calls,0);
assert.equal(await cloudIntent("Which trucks can take loads",opts),"available");
assert.equal(calls,1);
assert.equal(await cloudIntent("Which trucks can take loads",{...opts,generate:async()=> "delete"}),null);
assert.equal(await cloudIntent("Which trucks can take loads",{...opts,generate:async()=>{throw Error("quota");}}),null);
assert.equal(await cloudIntent("Which trucks can take loads",{...opts,generate:async()=>{auth=false;return "available";}}),null);
assert.equal(eligible("driver name"),false);
console.log("Gemini disabled-by-default, consent, scope, logout and fallback tests passed");
