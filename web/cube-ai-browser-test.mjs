import { chromium } from "playwright";
import assert from "node:assert/strict";
import {createServer} from "node:http";
import {readFile} from "node:fs/promises";
const server=createServer(async(req,res)=>{
 const path=new URL(req.url,"http://localhost").pathname;
 if(path==="/"){res.setHeader("Content-Type","text/html");res.end('<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="stylesheet" href="/cube-ai.css"></head><body></body></html>');return;}
 if(!["/cube-ai.mjs","/cube-ai.css","/fleet-query.mjs","/ai-language.mjs"].includes(path)){res.statusCode=404;res.end();return;}
 res.setHeader("Content-Type",path.endsWith(".mjs")?"text/javascript":"text/css");res.end(await readFile(new URL("."+path,import.meta.url)));
});
await new Promise(r=>server.listen(0,"127.0.0.1",r));
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1280,height:800}});
 const errors=[];page.on("pageerror",e=>errors.push(String(e)));
 await page.goto("http://127.0.0.1:"+server.address().port);
 await page.evaluate(async()=>{
  const {mountCubeAI}=await import("/cube-ai.mjs");
  const t={tripNumber:"TEST-1",vehicle:"TEST-VEHICLE",freight:1000,margin:250,totalExpenses:750,status:"Created",createdAt:1};
  window.fixture={authorized:true,canViewReports:true,tripsReady:true,vehiclesReady:true,period:"Test month",minMarginPercent:10,allTrips:[{...t,isOpen:true,vendor:"TEST-VENDOR",createdAt:Date.now(),fuelExpense:200}],summary:{trips:[t],active:1,transit:0,completed:0,revenue:1000,margin:250,low:0,delayed:0},kpiRows:{active:[t],transit:[],completed:[],low:[],delayed:[]},vehicles:[{number:"FREE-1",active:true,availability:"available"}]};
  window.widget=mountCubeAI(()=>window.fixture,null,async (q,lang)=>({ok:true,text:"General answer: "+q+(lang==="en"?"":" · "+lang)}));
 });
 assert.equal(await page.locator("#cubeAi").isVisible(),false);
 await page.evaluate(()=>window.widget.show());
 await page.getByRole("button",{name:"CUBE AI"}).click();
 await page.getByText("YOUR INTELLIGENT OPERATIONS PARTNER",{exact:true}).waitFor();
 await page.waitForFunction(()=>{const r=document.querySelector("#cubeAiPanel").getBoundingClientRect();return Math.abs(r.width-420)<1&&Math.abs(r.height-570)<1;});
 assert.ok(await page.getByRole("textbox",{name:"Ask CUBE AI"}).isVisible());
 assert.ok(await page.getByRole("combobox",{name:"Answer language"}).isVisible());
 assert.equal(await page.locator(".cube-ai-suggestions button").count(),6);
 await page.getByRole("button",{name:"Which vehicles are available now?"}).click();
 await page.getByText("FREE-1 · Available",{exact:true}).waitFor();
 assert.equal(await page.locator(".cube-ai-source[data-source=fleet]").count(),1);
 await page.getByRole("textbox",{name:"Ask CUBE AI"}).fill("Margin this month");
 await page.getByRole("button",{name:"Ask",exact:true}).click();
 await page.getByText("Total margin: ₹250.",{exact:false}).waitFor();
 assert.equal(await page.getByRole("button",{name:"General AI",exact:true}).count(),0);
 await page.getByRole("textbox",{name:"Ask CUBE AI"}).fill("What is diesel efficiency?");
 await page.getByRole("button",{name:"Ask",exact:true}).click();
 await page.getByText("General answer: What is diesel efficiency?",{exact:true}).waitFor();
 assert.equal(await page.locator(".cube-ai-source[data-source=gemini]").count(),0);
 assert.ok(await page.locator(".cube-ai-answer").last().getByRole("button",{name:"Copy answer"}).isVisible());
 assert.equal(await page.getByText("Google Gemini · Free tier",{exact:true}).count(),0);
 const lang=page.getByRole("combobox",{name:"Answer language"});
 assert.equal(await lang.locator("option").count(),5);
 assert.equal(await lang.inputValue(),"en");
 for(const [code,label] of [["hi","कुल लाभ"],["kn","ಒಟ್ಟು ಲಾಭ"],["ta","மொத்த லாபம்"],["te","మొత్తం లాభం"]]){
  await lang.selectOption(code);
  await page.getByRole("textbox",{name:"Ask CUBE AI"}).fill("Margin this month");
  await page.getByRole("button",{name:"Ask",exact:true}).click();
  await page.getByText(label+": ₹250.",{exact:false}).waitFor();
  await page.getByRole("textbox",{name:"Ask CUBE AI"}).fill("What is diesel efficiency?");
  await page.getByRole("button",{name:"Ask",exact:true}).click();
  await page.getByText("General answer: What is diesel efficiency? · "+code,{exact:true}).waitFor();
  assert.equal(await page.locator(".cube-ai-answer").last().locator(".cube-ai-source").count(),0);
  assert.ok(await page.locator(".cube-ai-answer").last().getByRole("button",{name:"Copy answer"}).isVisible());
 }
 assert.equal(await page.evaluate(()=>localStorage.getItem("cube.ai.answerLanguage")),"te");
 await lang.selectOption("en");
 await page.getByRole("button",{name:"Expand assistant"}).click();
 await page.waitForFunction(()=>document.querySelector("#cubeAiPanel").getBoundingClientRect().width>600);
 assert.ok((await page.locator("#cubeAiPanel").boundingBox()).width>600);
 await page.getByRole("button",{name:"Restore assistant"}).click();
 await page.waitForFunction(()=>Math.abs(document.querySelector("#cubeAiPanel").getBoundingClientRect().width-420)<1);
 await page.getByRole("textbox",{name:"Ask CUBE AI"}).fill("Revenue this month");
 await page.getByRole("button",{name:"Ask",exact:true}).click();
 await page.getByText("Total freight: ₹1,000.",{exact:false}).waitFor();
 await page.getByRole("textbox",{name:"Ask CUBE AI"}).press("Escape");
 assert.equal(await page.locator("#cubeAiPanel").isVisible(),false);
 await page.evaluate(()=>{window.widget.hide();window.fixture.canViewReports=false;window.widget.show();});
 await page.getByRole("button",{name:"CUBE AI"}).click();
 assert.equal(await page.getByText("FREE-1 · Available",{exact:true}).count(),0);
 await page.getByRole("textbox",{name:"Ask CUBE AI"}).fill("Revenue this month");
 await page.getByRole("button",{name:"Ask",exact:true}).click();
 await page.getByText("Your role does not allow financial reports.").waitFor();
 await page.getByRole("button",{name:"New conversation"}).click();
 assert.equal(await page.locator(".cube-ai-suggestions button").count(),4);
 await page.evaluate(()=>document.documentElement.dataset.theme="dark");
 await page.setViewportSize({width:375,height:667});
 assert.ok(await page.getByRole("textbox",{name:"Ask CUBE AI"}).isVisible());
 assert.equal(await page.locator(".cube-ai-suggestions button").count(),4);
 await page.emulateMedia({reducedMotion:"reduce"});
 assert.equal(await page.locator("#cubeAiPanel").evaluate(el=>getComputedStyle(el).animationName),"none");
 assert.equal(await page.locator("#cubeAiPanel").evaluate(el=>getComputedStyle(el).transitionDuration),"0s");
 const rect=await page.locator("#cubeAiPanel").boundingBox();
 assert.ok(rect.x>=0&&rect.x+rect.width<=375&&rect.y>=0&&rect.y+rect.height<=667,"mobile panel fits viewport");
 await page.evaluate(()=>window.widget.hide());
 assert.equal(await page.locator("#cubeAi").isVisible(),false);
 assert.deepEqual(errors,[]);
 console.log("CUBE AI desktop/mobile browser interaction and logout tests passed");
}finally{await browser.close();server.close();}
